import { describe, expect, it } from "vitest";
import type { BuildFacts } from "./facts";
import { buildFiles } from "./templates";

const base: BuildFacts = {
  kind: "nextjs", dir: ".", pm: "npm", node: 24, standalone: true, port: 3000, guessed: [],
  envNames: ["DATABASE_URL", "NEXT_PUBLIC_SITE_URL"], scripts: { build: true, start: true, lint: true, test: false, typecheck: null },
};
const meta = { app: "portfolio", version: "1.5.0", repo: "acme/shop-web", branch: "main" };
const files = (o: Partial<BuildFacts> = {}) => Object.fromEntries(buildFiles({ ...base, ...o }, meta).map((f) => [f.path, f]));
const text = (o: Partial<BuildFacts>, path: string) => files(o)[path].text;

describe("buildFiles", () => {
  it("writes five files, each with the Watchbell header", () => {
    const all = buildFiles(base, meta);
    expect(all.map((f) => f.path)).toEqual(["Dockerfile", ".dockerignore", "docker-compose.yml", ".github/workflows/ci.yml", "k8s.yaml"]);
    for (const f of all) expect(f.text.split("\n")[0]).toBe("# Generated by Watchbell 1.5.0 from portfolio's settings — review before use.");
  });

  it("runs a standalone Next.js build as a non-root numeric user", () => {
    const d = text({}, "Dockerfile");
    expect(d).toContain("FROM node:24-alpine AS deps");
    expect(d).toContain("COPY package.json package-lock.json .npmrc* ./");
    expect(d).toContain("RUN npm ci");
    expect(d).toContain("/app/.next/standalone");
    expect(d).toContain('CMD ["node", "server.js"]');
    expect(d).toContain("USER 10001");
    expect(d).toContain("ARG NEXT_PUBLIC_SITE_URL");
    expect(d).not.toContain("ARG DATABASE_URL");
    expect(d).toContain("HEALTHCHECK");
  });

  it("starts a Next.js app without standalone output, and suggests it", () => {
    const f = files({ standalone: false }).Dockerfile;
    expect(f.text).toContain('CMD ["npm", "start"]');
    expect(f.note).toBe('Add output: "standalone" to next.config for a smaller image; Watchbell never edits next.config.');
  });

  it("serves a Vite build with unprivileged nginx and an SPA fallback", () => {
    const d = text({ kind: "vite", port: 8080, envNames: ["VITE_API_URL"] }, "Dockerfile");
    expect(d).toContain("FROM nginxinc/nginx-unprivileged:stable-alpine AS run");
    expect(d).toContain("try_files $uri $uri/ /index.html");
    expect(d).toContain("/app/dist");
    expect(d).toContain("ARG VITE_API_URL");
    expect(text({ kind: "cra", port: 8080 }, "Dockerfile")).toContain("/app/build");
  });

  it("installs with each package manager's frozen command", () => {
    expect(text({ pm: "pnpm" }, "Dockerfile")).toContain("RUN corepack enable && pnpm install --frozen-lockfile");
    expect(text({ pm: "pnpm" }, "Dockerfile")).toContain("COPY package.json pnpm-lock.yaml .npmrc* pnpm-workspace.yaml* ./");
    expect(text({ pm: "yarn" }, "Dockerfile")).toContain("RUN corepack enable && yarn install --frozen-lockfile");
    expect(text({ pm: "bun" }, "Dockerfile")).toContain("FROM oven/bun:1-alpine AS deps");
    expect(text({ pm: "bun" }, "Dockerfile")).toContain("RUN bun install --frozen-lockfile");
  });

  it("uses npm install when the lockfile was guessed", () => {
    const d = text({ guessed: ["package manager"] }, "Dockerfile");
    expect(d).toContain("RUN npm install");
    expect(d).toContain("COPY package.json ./");
  });

  it("runs a plain Node app with its start script", () => {
    const d = text({ kind: "node", standalone: false, scripts: { ...base.scripts, build: false } }, "Dockerfile");
    expect(d).toContain('CMD ["npm", "start"]');
    expect(d).not.toContain("npm run build");
  });

  it("composes one app service, no database", () => {
    const c = text({}, "docker-compose.yml");
    expect(c).toContain("env_file: .env");
    expect(c).toContain("restart: unless-stopped");
    expect(c).toContain('"3000:3000"');
    expect(c).toContain("NEXT_PUBLIC_SITE_URL: ${NEXT_PUBLIC_SITE_URL}");
    expect(c).not.toMatch(/postgres|\bdb:/);
  });

  it("runs only the scripts that exist in CI, with pinned actions", () => {
    const y = text({}, ".github/workflows/ci.yml");
    expect(y).toContain("npm run lint");
    expect(y).not.toContain("npm test");
    expect(y).not.toContain("typecheck");
    expect(y).toContain("permissions:\n  contents: read");
    expect(y).toContain("branches: [main]");
    for (const m of y.matchAll(/uses: (\S+)/g)) expect(m[1]).toMatch(/^[A-Za-z0-9-]+\/[A-Za-z0-9._-]+@[0-9a-f]{40}$/);
    expect(text({ scripts: { ...base.scripts, test: true, typecheck: "type-check" } }, ".github/workflows/ci.yml")).toContain("npm run type-check");
  });

  it("names the env Secret and its keys without values", () => {
    const k = text({}, "k8s.yaml");
    expect(k).toContain("#   DATABASE_URL");
    expect(k).toContain("name: portfolio-env");
    expect(k).toContain("image: ghcr.io/acme/shop-web:latest");
    expect(k).toContain("runAsNonRoot: true");
    expect(k).toContain("containerPort: 3000");
  });

  it("puts files in the app's folder and runs CI there", () => {
    const f = files({ dir: "apps/web" });
    expect(Object.keys(f)).toEqual(["apps/web/Dockerfile", "apps/web/.dockerignore", "apps/web/docker-compose.yml", ".github/workflows/ci.yml", "apps/web/k8s.yaml"]);
    expect(f[".github/workflows/ci.yml"].text).toContain("working-directory: apps/web");
    expect(f[".github/workflows/ci.yml"].text).toContain("cache-dependency-path: apps/web/package-lock.json");
  });

  it("never lets an env value-looking string in", () => {
    const all = buildFiles(base, meta).map((f) => f.text).join("\n");
    expect(all).not.toMatch(/=\s*["'][^"'$]{6,}["']/);
  });
});

// Final review (1.5): fixes C1, I4, M4.
describe("review fixes", () => {
  const stages = (d: string) => d.split(/\n(?=FROM )/).filter((s) => s.startsWith("FROM "));
  it("enables corepack in every stage that runs pnpm or yarn (C1)", () => {
    for (const pm of ["pnpm", "yarn"] as const) {
      const [deps, build, run] = stages(text({ pm, standalone: false }, "Dockerfile"));
      expect(deps).toContain("corepack enable");
      expect(build).toContain("RUN corepack enable");
      expect(build.indexOf("corepack enable")).toBeLessThan(build.indexOf(`${pm} run build`));
      // The run stage starts with npm (always in the Node image), so no pnpm download at start-up.
      expect(run).toContain('CMD ["npm", "start"]');
    }
    expect(stages(text({ pm: "pnpm", standalone: true }, "Dockerfile"))[2]).not.toContain("corepack");
  });
  it("leaves the Secret out of k8s.yaml so re-applying it never blanks real values (I4)", () => {
    const k = text({}, "k8s.yaml");
    expect(k).not.toContain("kind: Secret");
    expect(k).toContain("kubectl create secret generic portfolio-env --from-env-file=.env");
    expect(k).toContain("#   DATABASE_URL");
    expect(k).toContain("name: portfolio-env");
  });
  it("makes a valid Kubernetes name from any app name (M4)", () => {
    const k = buildFiles(base, { ...meta, app: "9 Lives Shop" + "x".repeat(60) + "-" }).find((f) => f.path === "k8s.yaml")!.text;
    const name = /^ {2}name: (\S+)$/m.exec(k.split("kind: Deployment")[1])![1];
    expect(name).toMatch(/^[a-z]([-a-z0-9]{0,48}[a-z0-9])?$/);
  });
});

