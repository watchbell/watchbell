describe("minor fixes", () => {
  it("copies package-manager config next to the lockfile, and makes Yarn Berry install node_modules (M1)", () => {
    const d = text({ pm: "yarn", standalone: false }, "Dockerfile");
    expect(d).toContain("COPY package.json yarn.lock .npmrc* .yarnrc.yml* ./");
    expect(d).toContain("ENV YARN_NODE_LINKER=node-modules");
    expect(text({ pm: "pnpm" }, "Dockerfile")).toContain("COPY package.json pnpm-lock.yaml .npmrc* pnpm-workspace.yaml* ./");
    expect(text({ pm: "yarn" }, ".github/workflows/ci.yml")).not.toContain("cache: yarn");
  });
  it("installs corepack first on Node 25 and later, which no longer ships it (M2)", () => {
    expect(text({ pm: "pnpm", node: 26 }, "Dockerfile")).toContain("npm install -g corepack && corepack enable");
    expect(text({ pm: "pnpm", node: 24 }, "Dockerfile")).not.toContain("npm install -g corepack");
    expect(text({ pm: "pnpm", node: 26 }, ".github/workflows/ci.yml")).toContain("npm install -g corepack && corepack enable");
  });
  it("ignores logs and env files in every folder, keeping .env.example (M11)", () => {
    const i = text({}, ".dockerignore");
    expect(i).toContain("**/*.log");
    expect(i).toContain("**/.env*");
    expect(i).toContain("!**/.env.example");
  });
});
