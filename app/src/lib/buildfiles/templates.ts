import type { BuildFacts, PM } from "./facts";

// Watchbell 1.5 Build files (10b): the five files written from an app's facts — Dockerfile, .dockerignore,
// docker-compose.yml, a GitHub Actions CI workflow and a Kubernetes manifest. Text only: Watchbell never builds, runs or
// applies them. Env names appear (build args, the Secret's keys), values never do. Pure.

export type BuildFile = { path: string; text: string; note?: string };
// version: the running Watchbell (self-host); null on cloud, where the header just says "Watchbell".
export type BuildMeta = { app: string; version: string | null; repo: string | null; branch: string | null };

// Pinned to full commit SHAs (the 1.4 rule), read from each action's release page.
export const CI_ACTIONS = {
  checkout: "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1",
  setupNode: "actions/setup-node@949feb2413d6458794dcd2491c4babbbce0c15c1 # v7.1.0",
  setupBun: "oven-sh/setup-bun@0c5077e51419868618aeaa5fe8019c62421857d6 # v2.2.0",
};

const LOCK: Record<PM, string> = { npm: "package-lock.json", pnpm: "pnpm-lock.yaml", yarn: "yarn.lock", bun: "bun.lock" };
export const INSTALL: Record<PM, string> = {
  npm: "npm ci",
  pnpm: "pnpm install --frozen-lockfile",
  yarn: "yarn install --frozen-lockfile",
  bun: "bun install --frozen-lockfile",
};
// Package-manager settings that belong with the lockfile in the deps stage (globs: a missing one is skipped), M1.
const EXTRAS: Record<PM, string> = { npm: ".npmrc*", pnpm: ".npmrc* pnpm-workspace.yaml*", yarn: ".npmrc* .yarnrc.yml*", bun: ".npmrc* bunfig.toml*" };
// Node 25+ no longer ships corepack, so it's installed first there (M2).
const corepack = (node: number) => (node >= 25 ? "npm install -g corepack && corepack enable" : "corepack enable");
const installCommand = (pm: PM, node: number) => (pm === "pnpm" || pm === "yarn" ? `${corepack(node)} && ${INSTALL[pm]}` : INSTALL[pm]);
const RUN: Record<PM, (script: string) => string> = {
  npm: (s) => (s === "test" ? "npm test" : `npm run ${s}`),
  pnpm: (s) => `pnpm run ${s}`,
  yarn: (s) => `yarn run ${s}`,
  bun: (s) => `bun run ${s}`,
};
// npm runs any package manager's start script and is always in the Node image, so pnpm and yarn apps need no corepack
// (and no pnpm download) when the container starts (review C1). Bun apps run in the Bun image.
const START: Record<PM, string> = { npm: '["npm", "start"]', pnpm: '["npm", "start"]', yarn: '["npm", "start"]', bun: '["bun", "run", "start"]' };
// Names the browser bundle reads at build time, so they become build args.
const PUBLIC = /^(?:NEXT_PUBLIC_|VITE_|REACT_APP_)/;
const UID = 10001;

const header = (m: BuildMeta) => `# Generated by Watchbell${m.version ? ` ${m.version}` : ""} from ${m.app}'s settings — review before use.`;
const at = (dir: string, file: string) => (dir === "." ? file : `${dir}/${file}`);
// A Kubernetes name (DNS-1035 label): lower case, starts with a letter, ends with a letter or digit, at most 50 here.
const slug = (name: string) => {
  const s = name.toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "");
  return (/^[a-z]/.test(s) ? s : `app-${s}`).slice(0, 50).replace(/-+$/, "") || "app";
};

function dockerfile(f: BuildFacts, m: BuildMeta): BuildFile {
  const lockGuessed = f.guessed.includes("package manager");
  const install = lockGuessed ? "npm install" : installCommand(f.pm, f.node);
  const copyManifest = lockGuessed ? "COPY package.json ./" : `COPY package.json ${LOCK[f.pm]} ${EXTRAS[f.pm]} ./`;
  const nodeImage = `node:${f.node}-alpine`;
  const toolImage = f.pm === "bun" ? "oven/bun:1-alpine" : nodeImage;
  const args = f.envNames.filter((k) => PUBLIC.test(k)).flatMap((k) => [`ARG ${k}`, `ENV ${k}=$${k}`]);
  const lines = [
    header(m),
    `FROM ${toolImage} AS deps`,
    "WORKDIR /app",
    copyManifest,
    // Yarn 2+ would otherwise use Plug'n'Play and leave no node_modules to copy (Yarn 1 ignores it), M1.
    ...(f.pm === "yarn" && !lockGuessed ? ["ENV YARN_NODE_LINKER=node-modules"] : []),
    `RUN ${install}`,
    "",
    `FROM ${toolImage} AS build`,
    "WORKDIR /app",
    "COPY --from=deps /app/node_modules ./node_modules",
    "COPY . .",
    ...(f.kind === "nextjs" ? ["ENV NEXT_TELEMETRY_DISABLED=1", "RUN mkdir -p public"] : []),
    ...args,
    // Corepack is enabled per stage: the deps stage's doesn't carry over (review C1).
    ...(f.scripts.build ? [...(f.pm === "pnpm" || f.pm === "yarn" ? [`RUN ${corepack(f.node)}`] : []), `RUN ${RUN[f.pm]("build")}`] : []),
    "",
  ];
  const health = (port: number) => `HEALTHCHECK --interval=30s --timeout=5s --retries=3 CMD wget -q --spider http://127.0.0.1:${port}/ || exit 1`;
  const user = [`RUN addgroup -S -g ${UID} app && adduser -S -u ${UID} -G app app`];

  if (f.kind === "vite" || f.kind === "cra") {
    const out = f.kind === "vite" ? "dist" : "build";
    lines.push(
      "FROM nginxinc/nginx-unprivileged:stable-alpine AS run",
      "USER root",
      `RUN printf '%s\\n' 'server {' '  listen ${f.port};' '  root /usr/share/nginx/html;' '  location / { try_files $uri $uri/ /index.html; }' '}' > /etc/nginx/conf.d/default.conf`,
      "USER 101",
      `COPY --from=build /app/${out} /usr/share/nginx/html`,
      `EXPOSE ${f.port}`,
      health(f.port),
    );
    return { path: at(f.dir, "Dockerfile"), text: lines.join("\n") + "\n" };
  }
  if (f.kind === "nextjs" && f.standalone) {
    lines.push(
      `FROM ${nodeImage} AS run`,
      "WORKDIR /app",
      `ENV NODE_ENV=production NEXT_TELEMETRY_DISABLED=1 PORT=${f.port} HOSTNAME=0.0.0.0`,
      ...user,
      `COPY --from=build --chown=${UID}:${UID} /app/public ./public`,
      `COPY --from=build --chown=${UID}:${UID} /app/.next/standalone ./`,
      `COPY --from=build --chown=${UID}:${UID} /app/.next/static ./.next/static`,
      `USER ${UID}`,
      `EXPOSE ${f.port}`,
      health(f.port),
      'CMD ["node", "server.js"]',
    );
    return { path: at(f.dir, "Dockerfile"), text: lines.join("\n") + "\n" };
  }
  lines.push(
    `FROM ${toolImage} AS run`,
    "WORKDIR /app",
    `ENV NODE_ENV=production PORT=${f.port}${f.kind === "nextjs" ? " NEXT_TELEMETRY_DISABLED=1" : ""}`,
    ...user,
    `COPY --from=build --chown=${UID}:${UID} /app ./`,
    `USER ${UID}`,
    `EXPOSE ${f.port}`,
    health(f.port),
    `CMD ${START[f.pm]}`,
  );
  return {
    path: at(f.dir, "Dockerfile"), text: lines.join("\n") + "\n",
    ...(f.kind === "nextjs" ? { note: 'Add output: "standalone" to next.config for a smaller image; Watchbell never edits next.config.' } : {}),
  };
}

function dockerignore(f: BuildFacts, m: BuildMeta): BuildFile {
  const lines = [header(m), "node_modules", ".next", "dist", "build", ".git", ".github", ".vercel", "**/*.log", "**/.env*", "!**/.env.example", "Dockerfile", "docker-compose.yml", "k8s.yaml"];
  return { path: at(f.dir, ".dockerignore"), text: lines.join("\n") + "\n" };
}

function compose(f: BuildFacts, m: BuildMeta): BuildFile {
  const args = f.envNames.filter((k) => PUBLIC.test(k));
  const lines = [
    header(m),
    "# The app's database is a managed service (Supabase, Neon, …): its connection settings go in .env, not here.",
    "services:",
    "  app:",
    "    build:",
    "      context: .",
    ...(args.length ? ["      args:", ...args.map((k) => `        ${k}: \${${k}}`)] : []),
    "    ports:",
    `      - "${f.port}:${f.port}"`,
    "    env_file: .env",
    "    restart: unless-stopped",
  ];
  return { path: at(f.dir, "docker-compose.yml"), text: lines.join("\n") + "\n" };
}

function ci(f: BuildFacts, m: BuildMeta): BuildFile {
  const lockGuessed = f.guessed.includes("package manager");
  const install = lockGuessed ? "npm install" : installCommand(f.pm, f.node);
  const steps = [
    `      - uses: ${CI_ACTIONS.checkout}`,
    `      - uses: ${CI_ACTIONS.setupNode}`,
    "        with:",
    `          node-version: ${f.node}`,
    // Only npm's cache: setup-node's yarn cache runs the runner's Yarn 1 before corepack, which breaks Yarn 2+ (M1).
    ...(!lockGuessed && f.pm === "npm" ? [`          cache: ${f.pm}`, `          cache-dependency-path: ${at(f.dir, LOCK[f.pm])}`] : []),
    ...(f.pm === "bun" ? [`      - uses: ${CI_ACTIONS.setupBun}`] : []),
    `      - run: ${install}`,
    ...(f.scripts.lint ? [`      - run: ${RUN[f.pm]("lint")}`] : []),
    ...(f.scripts.typecheck ? [`      - run: ${RUN[f.pm](f.scripts.typecheck)}`] : []),
    ...(f.scripts.test ? [`      - run: ${RUN[f.pm]("test")}`] : []),
  ];
  if (f.scripts.build) {
    const pub = f.envNames.filter((k) => PUBLIC.test(k));
    steps.push(`      - run: ${RUN[f.pm]("build")}`);
    if (pub.length) steps.push("        env:", ...pub.map((k) => `          ${k}: \${{ vars.${k} }}`));
  }
  const lines = [
    header(m),
    "name: CI",
    "on:",
    "  pull_request:",
    "  push:",
    `    branches: [${m.branch ?? "main"}]`,
    "permissions:",
    "  contents: read",
    "jobs:",
    "  build:",
    "    runs-on: ubuntu-latest",
    "    timeout-minutes: 15",
    ...(f.dir !== "." ? ["    defaults:", "      run:", `        working-directory: ${f.dir}`] : []),
    "    steps:",
    ...steps,
  ];
  return { path: ".github/workflows/ci.yml", text: lines.join("\n") + "\n" };
}

function k8s(f: BuildFacts, m: BuildMeta): BuildFile {
  const name = slug(m.app);
  const image = m.repo ? `ghcr.io/${m.repo.toLowerCase()}:latest` : `ghcr.io/OWNER/${name}:latest`;
  const probe = (kind: string) => [`          ${kind}:`, "            httpGet:", "              path: /", `              port: ${f.port}`, "            periodSeconds: 15"];
  const lines = [
    header(m),
    // No Secret object here (review I4): re-applying this file would reset its values. Create it once from .env.
    "# The app's env values live in a Secret you create once on the cluster, never in this file:",
    `#   kubectl create secret generic ${name}-env --from-env-file=.env`,
    ...(f.envNames.length ? ["# It needs these names:", ...f.envNames.map((k) => `#   ${k}`)] : []),
    "apiVersion: apps/v1",
    "kind: Deployment",
    "metadata:",
    `  name: ${name}`,
    "  labels:",
    `    app: ${name}`,
    "spec:",
    "  replicas: 1",
    "  selector:",
    "    matchLabels:",
    `      app: ${name}`,
    "  template:",
    "    metadata:",
    "      labels:",
    `        app: ${name}`,
    "    spec:",
    "      securityContext:",
    "        runAsNonRoot: true",
    "      containers:",
    "        - name: app",
    `          image: ${image} # change to the image you push`,
    "          ports:",
    `            - containerPort: ${f.port}`,
    "          envFrom:",
    "            - secretRef:",
    `                name: ${name}-env`,
    "          resources:",
    "            requests:",
    "              cpu: 100m",
    "              memory: 128Mi",
    "            limits:",
    "              cpu: 500m",
    "              memory: 512Mi",
    ...probe("readinessProbe"),
    ...probe("livenessProbe"),
    "---",
    "apiVersion: v1",
    "kind: Service",
    "metadata:",
    `  name: ${name}`,
    "spec:",
    "  selector:",
    `    app: ${name}`,
    "  ports:",
    "    - port: 80",
    `      targetPort: ${f.port}`,
  ];
  return { path: at(f.dir, "k8s.yaml"), text: lines.join("\n") + "\n" };
}

export function buildFiles(f: BuildFacts, m: BuildMeta): BuildFile[] {
  return [dockerfile(f, m), dockerignore(f, m), compose(f, m), ci(f, m), k8s(f, m)];
}
