import { describe, expect, it } from "vitest";
import { type BuildFilesDeps, generateBuildFiles } from "./buildfiles-db";

const pkg = JSON.stringify({ engines: { node: "^22" }, scripts: { build: "next build", start: "next start", lint: "eslint ." } });

function deps(o: Partial<BuildFilesDeps> & { files?: Record<string, string> } = {}): BuildFilesDeps & { read: string[] } {
  const read: string[] = [];
  return {
    read,
    target: async () => ({ name: "portfolio", framework: "nextjs", rootDir: null, rootDirUnusable: null, token: "v", teamId: "team_1", projectId: "prj_1" }),
    repo: async () => ({ fullName: "acme/shop-web", branch: "main" }),
    githubToken: async () => "g",
    file: async (_t, _r, path) => {
      read.push(path);
      const text = (o.files ?? { "package.json": pkg, "package-lock.json": "{}", "next.config.ts": `export default { output: "standalone" }` })[path];
      return text === undefined ? { ok: false, kind: "missing", error: "Not found" } : { ok: true, data: text };
    },
    envNames: async () => ({ ok: true, data: [{ key: "DATABASE_URL", targets: ["production"], branch: null }, { key: "PREVIEW_ONLY", targets: ["preview"], branch: null }] }),
    version: () => "1.5.0",
    ...o,
  };
}

describe("generateBuildFiles", () => {
  it("reads the app's facts and writes its files", async () => {
    const d = deps();
    const r = await generateBuildFiles("app", d);
    if (!r.ok) throw new Error(r.error);
    expect(r.data.facts).toMatchObject({ kind: "nextjs", node: 22, pm: "npm", standalone: true, envNames: ["DATABASE_URL"], guessed: [] });
    expect(r.data.repo).toBe("acme/shop-web");
    expect(r.data.files).toHaveLength(5);
    expect(r.data.files[0].text).toContain("Generated by Watchbell 1.5.0 from portfolio's settings");
    expect(d.read).not.toContain(".env.example");
  });

  it("reads everything inside the Vercel Root Directory", async () => {
    const d = deps({
      target: async () => ({ name: "finance", framework: "nextjs", rootDir: "apps/web", rootDirUnusable: null, token: "v", teamId: "t", projectId: "p" }),
      files: { "apps/web/package.json": pkg, "apps/web/pnpm-lock.yaml": "lockfileVersion: 9" },
    });
    const r = await generateBuildFiles("app", d);
    if (!r.ok) throw new Error(r.error);
    expect(r.data.facts).toMatchObject({ dir: "apps/web", pm: "pnpm", standalone: false });
    expect(d.read).toContain("apps/web/next.config.ts");
    expect(r.data.files.map((f) => f.path)).toContain("apps/web/Dockerfile");
  });

  it("falls back to .env.example names when Vercel's can't be read", async () => {
    const r = await generateBuildFiles("app", deps({
      envNames: async () => ({ ok: false, kind: "auth", error: "no" }),
      files: { "package.json": pkg, ".env.example": "A=\nB=1\n" },
    }));
    expect(r.ok && r.data.facts.envNames).toEqual(["A", "B"]);
  });

  it("still writes files without a linked repository, and says what it guessed", async () => {
    const r = await generateBuildFiles("app", deps({ repo: async () => null }));
    if (!r.ok) throw new Error(r.error);
    expect(r.data.repo).toBeNull();
    expect(r.data.facts.guessed).toEqual(["package manager", "Node version", "scripts"]);
  });

  it("refuses an app it can't read or a folder it can't use", async () => {
    expect(await generateBuildFiles("app", deps({ target: async () => null }))).toEqual({ ok: false, error: "That app's Vercel project can't be read. Sync Vercel and try again." });
    expect(await generateBuildFiles("app", deps({
      target: async () => ({ name: "x", framework: "nextjs", rootDir: null, rootDirUnusable: "../up", token: "v", teamId: "t", projectId: "p" }),
    }))).toEqual({ ok: false, error: "The Vercel Root Directory isn't a folder Watchbell can read." });
  });

  it("passes on a framework without templates", async () => {
    const r = await generateBuildFiles("app", deps({
      target: async () => ({ name: "x", framework: "sveltekit", rootDir: null, rootDirUnusable: null, token: "v", teamId: "t", projectId: "p" }),
    }));
    expect(r).toEqual({ ok: false, error: "Watchbell can't write build files for sveltekit yet." });
  });

  it("writes a header without a version where none is known (cloud)", async () => {
    const r = await generateBuildFiles("app", deps({ version: () => null }));
    expect(r.ok && r.data.files[0].text.split("\n")[0]).toBe("# Generated by Watchbell from portfolio's settings — review before use.");
  });
});

describe("review fix I1", () => {
  it("finds a lockfile too large to read in full", async () => {
    const d = deps({
      files: { "package.json": pkg },
      file: async (_t, _r, path) => (path === "pnpm-lock.yaml" ? { ok: true, data: null } : path === "package.json" ? { ok: true, data: pkg } : { ok: false, kind: "missing", error: "Not found" }),
    });
    const r = await generateBuildFiles("app", d);
    expect(r.ok && r.data.facts.pm).toBe("pnpm");
    expect(r.ok && r.data.facts.guessed).not.toContain("package manager");
  });
});
