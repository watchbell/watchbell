import { describe, expect, it } from "vitest";
import {
  depsFromManifest, directNames, isPackageName, isVersion, MAX_DEPS, minVersion, parseBunLock, parseLockfile, parseManifest, parsePackageLock, parsePnpmLock,
  parseYarnLock, pnpmKey,
} from "./lockfile";

describe("parsePackageLock", () => {
  it("v2/v3: every installed path, nested copies too, real names of aliases, no root or workspace links", () => {
    const text = JSON.stringify({
      lockfileVersion: 3,
      packages: {
        "": { name: "app", version: "1.0.0", dependencies: { next: "^15.0.0" } },
        "node_modules/next": { version: "15.0.0" },
        "node_modules/@babel/core": { version: "7.24.0", dev: true },
        "node_modules/next/node_modules/postcss": { version: "8.4.31" },
        "node_modules/postcss": { version: "8.4.49", dev: true },
        "node_modules/my-alias": { name: "lodash", version: "4.17.20" },
        "packages/ui": { version: "0.0.0" },
        "node_modules/ui": { resolved: "packages/ui", link: true },
      },
    });
    expect(parsePackageLock(text)).toEqual([
      { name: "@babel/core", version: "7.24.0", dev: true },
      { name: "lodash", version: "4.17.20", dev: false },
      { name: "next", version: "15.0.0", dev: false },
      { name: "postcss", version: "8.4.31", dev: false },
      { name: "postcss", version: "8.4.49", dev: true },
    ]);
  });

  it("v1: walks the nested tree", () => {
    const text = JSON.stringify({ lockfileVersion: 1, dependencies: { a: { version: "1.0.0", dependencies: { b: { version: "2.0.0", dev: true } } } } });
    expect(parsePackageLock(text)).toEqual([{ name: "a", version: "1.0.0", dev: false }, { name: "b", version: "2.0.0", dev: true }]);
  });

  it("a package counted as runtime anywhere is runtime; junk and non-versions are dropped; not JSON → null", () => {
    const text = JSON.stringify({ packages: {
      "node_modules/a": { version: "1.0.0", dev: true }, "node_modules/x/node_modules/a": { version: "1.0.0" },
      "node_modules/git-dep": { version: "git+https://example.com/x.git" }, "node_modules/BAD NAME": { version: "1.0.0" },
    } });
    expect(parsePackageLock(text)).toEqual([{ name: "a", version: "1.0.0", dev: false }]);
    expect(parsePackageLock("{nope")).toBeNull();
    expect(parsePackageLock("[]")).toBeNull();
    expect(parsePackageLock("{}")).toBeNull();
  });
});

describe("pnpm-lock.yaml", () => {
  it("reads v9, v6 and v5 keys", () => {
    expect(pnpmKey("next@16.0.0")).toEqual({ name: "next", version: "16.0.0" });
    expect(pnpmKey("'@babel/core@7.24.0'")).toEqual({ name: "@babel/core", version: "7.24.0" });
    expect(pnpmKey("/next@14.0.0(react-dom@18.2.0)(react@18.2.0)")).toEqual({ name: "next", version: "14.0.0" });
    expect(pnpmKey("/@types/node/20.1.0")).toEqual({ name: "@types/node", version: "20.1.0" });
    expect(pnpmKey("/foo/1.0.0_bar@2.0.0")).toEqual({ name: "foo", version: "1.0.0" });
  });

  it("collects the packages section with v6 dev flags; no lockfileVersion → null", () => {
    const v9 = [
      "lockfileVersion: '9.0'", "", "importers:", "  .:", "    dependencies:", "      next:", "        specifier: ^16.0.0", "        version: 16.0.0", "",
      "packages:", "", "  next@16.0.0:", "    resolution: {integrity: sha512-x}", "", "  '@next/env@16.0.0':", "    resolution: {integrity: sha512-y}", "",
      "snapshots:", "", "  next@16.0.0(react@19.0.0):", "    dependencies:", "      '@next/env': 16.0.0",
    ].join("\n");
    expect(parsePnpmLock(v9)).toEqual([{ name: "@next/env", version: "16.0.0", dev: false }, { name: "next", version: "16.0.0", dev: false }]);
    const v6 = ["lockfileVersion: '6.0'", "packages:", "  /vitest@1.0.0:", "    resolution: {integrity: sha512-z}", "    dev: true", "  /zod@3.22.0:", "    dev: false"].join("\r\n");
    expect(parsePnpmLock(v6)).toEqual([{ name: "vitest", version: "1.0.0", dev: true }, { name: "zod", version: "3.22.0", dev: false }]);
    expect(parsePnpmLock("packages:\n  a@1.0.0:\n")).toBeNull();
  });
});

describe("yarn.lock", () => {
  it("reads classic v1 and berry", () => {
    const v1 = [
      "# THIS IS AN AUTOGENERATED FILE.", "# yarn lockfile v1", "",
      '"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.10.4":', '  version "7.12.13"', '  resolved "https://registry.yarnpkg.com/x"', "",
      "lodash@^4.17.0:", '  version "4.17.20"',
    ].join("\n");
    expect(parseYarnLock(v1)).toEqual([{ name: "@babel/code-frame", version: "7.12.13", dev: false }, { name: "lodash", version: "4.17.20", dev: false }]);
    const berry = [
      "__metadata:", "  version: 8", "", '"next@npm:16.0.0":', "  version: 16.0.0", '  resolution: "next@npm:16.0.0"', "",
      '"app@workspace:.":', "  version: 0.0.0-use.local",
    ].join("\n");
    expect(parseYarnLock(berry)).toEqual([{ name: "next", version: "16.0.0", dev: false }]);
    expect(parseYarnLock("")).toBeNull();
  });
});

describe("bun.lock", () => {
  it("reads the text lockfile with trailing commas", () => {
    const text = `{
  "lockfileVersion": 1,
  "workspaces": { "": { "name": "app", "dependencies": { "next": "^16.0.0", }, }, },
  "packages": {
    "next": ["next@16.0.0", "", {}, "sha512-a"],
    "@scope/x": ["@scope/x@1.2.3", "", {}, "sha512-b"],
  },
}`;
    expect(parseBunLock(text)).toEqual([{ name: "@scope/x", version: "1.2.3", dev: false }, { name: "next", version: "16.0.0", dev: false }]);
    expect(parseBunLock("not json")).toBeNull();
  });
});

describe("package.json fallback", () => {
  it("takes the lowest version of simple ranges only", () => {
    expect(minVersion("^1.2.3")).toBe("1.2.3");
    expect(minVersion("~1.2")).toBe("1.2.0");
    expect(minVersion(">=2.0.0")).toBe("2.0.0");
    expect(minVersion("v3.1.4")).toBe("3.1.4");
    expect(minVersion("1.x")).toBe("1.0.0");
    expect(minVersion("15.0.0-canary.1")).toBe("15.0.0-canary.1");
    for (const r of ["latest", "*", "workspace:*", "file:../x", "github:a/b", "^1.0.0 || ^2.0.0", "1.0.0 - 2.0.0"]) expect(minVersion(r)).toBeNull();
  });

  it("lists the manifest's dependencies (dev marked) and its direct names", () => {
    const m = parseManifest(JSON.stringify({ dependencies: { next: "^16.0.0", odd: "latest" }, devDependencies: { vitest: "~3.1.0" }, optionalDependencies: { fsevents: "2.3.3" } }))!;
    expect(depsFromManifest(m)).toEqual([
      { name: "fsevents", version: "2.3.3", dev: false }, { name: "next", version: "16.0.0", dev: false }, { name: "vitest", version: "3.1.0", dev: true },
    ]);
    expect([...directNames(m)].sort()).toEqual(["fsevents", "next", "odd", "vitest"]);
    expect(directNames(null).size).toBe(0);
    expect(parseManifest("[1]")).toBeNull();
  });
});

describe("guards", () => {
  it("names and versions", () => {
    expect(isPackageName("@scope/pkg.name_x-y")).toBe(true);
    expect(isPackageName("../etc")).toBe(false);
    expect(isPackageName("a b")).toBe(false);
    expect(isVersion("1.2.3")).toBe(true);
    expect(isVersion("1.2")).toBe(false);
  });

  it("caps the list", () => {
    const packages = Object.fromEntries(Array.from({ length: MAX_DEPS + 50 }, (_, i) => [`node_modules/p${i}`, { version: "1.0.0" }]));
    expect(parsePackageLock(JSON.stringify({ packages }))).toHaveLength(MAX_DEPS);
  });

  it("parseLockfile dispatches by kind", () => {
    expect(parseLockfile("npm", JSON.stringify({ packages: { "node_modules/a": { version: "1.0.0" } } }))).toEqual([{ name: "a", version: "1.0.0", dev: false }]);
    expect(parseLockfile("yarn", 'a@^1:\n  version "1.0.0"')).toEqual([{ name: "a", version: "1.0.0", dev: false }]);
  });
});
